/**
 * Synchronous SHA-256.
 *
 * The audit ledger is a hash chain: each record commits to the digest of the
 * record before it, so removing or editing any entry invalidates every entry
 * after it. That property is only worth anything if the digest is a real
 * cryptographic hash, so this is a full SHA-256 rather than a checksum.
 *
 * It is implemented here rather than taken from node:crypto or WebCrypto for
 * two reasons: the engine must run identically in a browser and on a server,
 * and WebCrypto digest is async, which would force the entire ledger append
 * path to become asynchronous for no benefit.
 */

